/**
 * Returns the resolved statutory official portal and helpline for a temple
 */
export function getTempleAuthorityInfo(temple) {
  if (!temple) return null;
  const state = temple.location?.state;
  const stateEndowment = STATE_ENDOWMENTS[state] || null;

  const website = temple.contactInfo?.website || '';
  const isWikipedia = website.toLowerCase().includes('wikipedia.org');
  const hasSpecificWebsite = Boolean(website && !isWikipedia);

  return {
    isSpecificTrustWebsite: hasSpecificWebsite,
    trustWebsite: hasSpecificWebsite ? website : (stateEndowment?.website || 'https://asi.nic.in'),
    trustName: hasSpecificWebsite ? `${temple.name} Official Trust` : (stateEndowment?.boardName || 'Archaeological Survey of India & Endowments'),
    wikipediaUrl: isWikipedia ? website : null,
    helpline: temple.contactInfo?.helpline && temple.contactInfo.helpline !== '+91-1800-425-TEERTH'
      ? temple.contactInfo.helpline
      : (stateEndowment?.helpline || '+91-1800-425-TEERTH')
  };
}

